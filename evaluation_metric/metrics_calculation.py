from bert_score import score as bertscore


#########################################
# 1. Chart Accuracy
#########################################
def chart_accuracy(gold_chart: dict, pred_chart: dict):
    """
    gold_chart: dict of palace -> list of stars
    pred_chart: dict of palace -> list of stars
    """
    correct = 0
    total = 0

    for palace in gold_chart:
        gold_stars = set(gold_chart[palace])
        pred_stars = set(pred_chart.get(palace, []))

        total += 1
        if gold_stars == pred_stars:
            correct += 1

    return correct / total if total > 0 else 0.0


#########################################
# 2. Star Mention Accuracy
#########################################
def star_mention_accuracy(gold_chart: dict, pred_interpretation: str):
    """
    檢查模型解讀中是否提到正確的星、是否提到不存在的星
    """
    # 收集標準命盤中的所有星曜名稱
    gold_stars = set()
    for stars in gold_chart.values():
        gold_stars.update(stars)

    mentioned_stars = set()

    for star in gold_stars:
        if star in pred_interpretation:
            mentioned_stars.add(star)

    # recall-like measure
    return len(mentioned_stars) / len(gold_stars) if len(gold_stars) > 0 else 0.0


#########################################
# 3. Cosine Similarity
#########################################
cos_model = SentenceTransformer("all-MiniLM-L6-v2")

def cosine_sim(gold_text: str, pred_text: str):
    emb1 = cos_model.encode([gold_text])
    emb2 = cos_model.encode([pred_text])
    sim = cosine_similarity(emb1, emb2)[0][0]
    return float(sim)


#########################################
# 4. BERTScore
#########################################
def compute_bertscore(gold_text: str, pred_text: str):
    P, R, F1 = bertscore([pred_text], [gold_text], lang="zh")
    return float(F1[0])


