# 全部 metrics 入口
#########################################
def evaluate(
    birth_data, 
    gold_chart, 
    gold_interpretation, 
    pred_chart, 
    pred_interpretation
):
    results = {}

    results["chart_accuracy"] = chart_accuracy(gold_chart, pred_chart)
    results["star_mention_accuracy"] = star_mention_accuracy(gold_chart, pred_interpretation)
    results["cosine_similarity"] = cosine_sim(gold_interpretation, pred_interpretation)
    results["bertscore"] = compute_bertscore(gold_interpretation, pred_interpretation)
    results["human_rating"] = human_rating()

    return results


